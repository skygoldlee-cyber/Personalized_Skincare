  if (aEnd === -1) aEnd = content.indexOf('\n---\n', aStart);
  if (aEnd === -1) aEnd = content.length;

  content = content.substring(0, aStart) + data.a + content.substring(aEnd);
  content = content.substring(0, qStart) + data.q + content.substring(qEnd);
